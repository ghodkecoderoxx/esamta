# 10. STATEWIDE TIME-SERIES PLOTS
# ============================================================

def plot_statewide_series(
    period_df,
    trend_df,
    period_name,
    output_filename,
    title
):

    state_entity = get_statewide_row(period_df)

    state_data = period_df[
        period_df["entity"] == state_entity
    ].sort_values("year")

    trend_row = trend_df[
        (trend_df["entity"] == state_entity)
        & (
            trend_df["entity_type"]
            .astype(str)
            .str.lower()
            == "state"
        )
    ]

    # Fallback if entity_type does not use "state".
    if trend_row.empty:
        trend_row = trend_df[
            trend_df["entity"] == state_entity
        ]

    if trend_row.empty:
        raise ValueError(
            f"No trend result found for {state_entity}."
        )

    slope = float(
        trend_row.iloc[0]["ols_slope_mm_per_year"]
    )

    years = state_data["year"].to_numpy(dtype=float)
    values = state_data["precipitation_mm"].to_numpy(
        dtype=float
    )

    fitted = (
        trend_row.iloc[0]["ols_intercept_mm"]
        + slope * (years - years[0])
    )

    fig, ax = plt.subplots(figsize=(12, 6))

    ax.plot(
        years,
        values,
        marker="o",
        markersize=4,
        linewidth=1.5,
        label="Observed precipitation"
    )

    ax.plot(
        years,
        fitted,
        linestyle="--",
        linewidth=2,
        label="OLS linear trend"
    )

    ax.set_title(title)
    ax.set_xlabel("Year")
    ax.set_ylabel("Precipitation (mm)")
    ax.grid(alpha=0.3)
    ax.legend()

    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR / output_filename,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


