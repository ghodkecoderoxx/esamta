# 7. MANN-KENDALL AND SEN'S SLOPE
# ============================================================

def calculate_mann_kendall(values):
    """
    Hamed-Rao modified Mann-Kendall test and Sen's slope.

    The input is annual or JJAS precipitation, not raw
    monthly precipitation. This avoids applying a standard
    non-seasonal MK test directly to a seasonal monthly series.
    """

    values = np.asarray(values, dtype=float)

    if len(values) < MIN_YEARS:
        raise ValueError("Insufficient observations.")

    result = mk.hamed_rao_modification_test(values)

    sen_result = mk.sens_slope(values)

    return {
        "mk_trend": str(result.trend),
        "mk_hamed_rao_z": float(result.z),
        "mk_tau": float(result.Tau),
        "mk_p_value": float(result.p),
        "sen_slope_mm_per_year": float(sen_result.slope),
        "sen_slope_mm_per_decade": float(
            sen_result.slope * 10.0
        ),
    }


