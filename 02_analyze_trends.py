# 6. LINEAR TREND WITH HAC STANDARD ERRORS
# ============================================================

def calculate_hac_trend(years, values, maxlags):
    """
    Estimate an OLS linear trend with HAC/Newey-West
    covariance estimation.

    The explanatory variable is elapsed years.

    Slope units: mm/year.
    """

    years = np.asarray(years, dtype=float)
    values = np.asarray(values, dtype=float)

    if len(values) < MIN_YEARS:
        raise ValueError("Insufficient observations.")

    # Time is expressed in years from the first observation.
    x = years - years[0]

    X = sm.add_constant(x)

    ordinary_model = sm.OLS(values, X).fit()

    # HAC lag must be smaller than the sample size.
    safe_lag = min(
        int(maxlags),
        max(0, len(values) - 2)
    )

    with warnings.catch_warnings():
        warnings.simplefilter("ignore")

        robust_model = ordinary_model.get_robustcov_results(
            cov_type="HAC",
            maxlags=safe_lag
        )

    slope = float(ordinary_model.params[1])
    intercept = float(ordinary_model.params[0])

    confidence_interval = robust_model.conf_int(
        alpha=0.05
    )

    lower_ci = float(confidence_interval[1, 0])
    upper_ci = float(confidence_interval[1, 1])

    p_value = float(robust_model.pvalues[1])

    fitted = ordinary_model.predict(X)
    residuals = values - fitted

    return {
        "ols_slope_mm_per_year": slope,
        "ols_slope_mm_per_decade": slope * 10.0,
        "ols_intercept_mm": intercept,
        "hac_standard_error_mm_per_year": float(
            robust_model.bse[1]
        ),
        "hac_ci_lower_mm_per_year": lower_ci,
        "hac_ci_upper_mm_per_year": upper_ci,
        "hac_ci_lower_mm_per_decade": lower_ci * 10.0,
        "hac_ci_upper_mm_per_decade": upper_ci * 10.0,
        "hac_p_value": p_value,
        "ols_r_squared": float(ordinary_model.rsquared),
        "residual_lag1_autocorrelation": (
            lag1_autocorrelation(residuals)
        ),
        "hac_maxlags": safe_lag,
    }


