def normalize_name(value):
    """Normalize district names for matching."""

    return re.sub(
        r"[^a-z0-9]",
        "",
        str(value).lower()
    )


def plot_district_map(
    trend_df,
    period_name,
    output_filename,
    title
):

    if not BOUNDARY_PATH.exists():
        print(
            f"\nBoundary file not found: {BOUNDARY_PATH}\n"
            "Skipping district map. Set BOUNDARY_PATH "
            "to your GeoJSON file to enable it."
        )
        return

    try:
        import geopandas as gpd

    except ImportError:
        print(
            "\nGeoPandas is not installed. "
            "Skipping district map."
        )
        return

    districts = trend_df[
        trend_df["entity_type"]
        .astype(str)
        .str.lower()
        .eq("district")
    ].copy()

    if districts.empty:
        print(f"No district trend results for {period_name}.")
        return

    boundaries = gpd.read_file(BOUNDARY_PATH)

    if "dtname" not in boundaries.columns:
        raise ValueError(
            "Expected district-name column 'dtname' "
            "not found in GeoJSON."
        )

    districts["join_name"] = (
        districts["entity"].apply(normalize_name)
    )

    boundaries["join_name"] = (
        boundaries["dtname"].apply(normalize_name)
    )

    merged = boundaries.merge(
        districts,
        on="join_name",
        how="left",
        validate="one_to_one"
    )

    unmatched = merged[
        merged["sen_slope_mm_per_decade"].isna()
    ]

    if len(unmatched) > 0:
        print(
            "\nWARNING: Some boundary districts did not "
            "match trend results:"
        )
        print(unmatched["dtname"].tolist())

    fig, ax = plt.subplots(figsize=(10, 10))

    merged.plot(
        column="sen_slope_mm_per_decade",
        cmap="RdBu",
        legend=True,
        edgecolor="black",
        linewidth=0.45,
        missing_kwds={
            "color": "lightgrey",
            "label": "No matched data"
        },
        ax=ax
    )

    ax.set_title(
        title + "\n"
        "Sen's slope (mm/decade)"
    )

    ax.set_axis_off()

    fig.tight_layout()

    fig.savefig(
        OUTPUT_DIR / output_filename,
        dpi=300,
        bbox_inches="tight"
    )

    plt.close(fig)


