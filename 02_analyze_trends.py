# 4. HELPER: LAG-1 RESIDUAL AUTOCORRELATION
# ============================================================

def lag1_autocorrelation(residuals):
    """
    Calculate lag-1 autocorrelation of detrended residuals.

    Residual autocorrelation is more informative here than
    autocorrelation of the raw trending precipitation series.
    """

    residuals = np.asarray(residuals, dtype=float)

    if len(residuals) < 3:
        return np.nan

    x = residuals[:-1]
    y = residuals[1:]

    if np.std(x) == 0 or np.std(y) == 0:
        return np.nan

    return float(np.corrcoef(x, y)[0, 1])


# ============================================================
# 5. HELPER: BENJAMINI-HOCHBERG FDR CORRECTION
# ============================================================

def benjamini_hochberg(p_values):
    """
    Benjamini-Hochberg adjusted p-values.

    NaN values are retained as NaN.
    """

    p = np.asarray(p_values, dtype=float)

    q = np.full(p.shape, np.nan, dtype=float)

    valid_indices = np.where(np.isfinite(p))[0]

    if len(valid_indices) == 0:
        return q

    valid_p = p[valid_indices]

    order = np.argsort(valid_p)
    sorted_p = valid_p[order]

    m = len(sorted_p)
    ranks = np.arange(1, m + 1)

    adjusted = sorted_p * m / ranks

    # Enforce monotonicity from largest to smallest p-value.
    adjusted = np.minimum.accumulate(
        adjusted[::-1]
    )[::-1]

    adjusted = np.clip(adjusted, 0.0, 1.0)

    restored = np.empty(m, dtype=float)
    restored[order] = adjusted

    q[valid_indices] = restored

    return q


