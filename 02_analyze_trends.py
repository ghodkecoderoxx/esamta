def main():

    print("=" * 65)
    print("MAHARASHTRA PRECIPITATION TREND ANALYSIS")
    print("=" * 65)

    # Load and validate the monthly panel.
    monthly = load_monthly_data(INPUT_CSV)

    # Build complete annual and JJAS series.
    annual, monsoon = aggregate_complete_periods(
        monthly
    )

    # Annual analysis.
    print("\nANALYSING ANNUAL PRECIPITATION...")
    annual_results, annual_sensitivity = analyse_period(
        annual,
        "annual"
    )

    # Monsoon analysis.
    print("\nANALYSING JJAS MONSOON PRECIPITATION...")
    monsoon_results, monsoon_sensitivity = analyse_period(
        monsoon,
        "monsoon"
    )

    # Combine trend results.
    all_results = pd.concat(
        [annual_results, monsoon_results],
        ignore_index=True
    )

    all_sensitivity = pd.concat(
        [annual_sensitivity, monsoon_sensitivity],
        ignore_index=True
    )

    # Save outputs.
    all_results.to_csv(
        OUTPUT_DIR / "trend_results.csv",
        index=False
    )

    all_sensitivity.to_csv(
        OUTPUT_DIR / "hac_sensitivity.csv",
        index=False
    )

    # Statewide annual time series.
    plot_statewide_series(
        annual,
        annual_results,
        "annual",
        "annual_timeseries.png",
        "Maharashtra Annual Precipitation (1998–2024)"
    )

    # Statewide monsoon time series.
    plot_statewide_series(
        monsoon,
        monsoon_results,
        "monsoon",
        "monsoon_timeseries.png",
        "Maharashtra JJAS Precipitation (1998–2024)"
    )

    # District maps.
    plot_district_map(
        annual_results,
        "annual",
        "annual_district_trends.png",
        "Annual precipitation trends across Maharashtra"
    )

    plot_district_map(
        monsoon_results,
        "monsoon",
        "monsoon_district_trends.png",
        "JJAS precipitation trends across Maharashtra"
    )

    # --------------------------------------------------------
    # Summary
    # --------------------------------------------------------

    print("\n" + "=" * 65)
    print("ANALYSIS COMPLETE")
    print("=" * 65)

    print(f"\nOutput directory:\n{OUTPUT_DIR}")

    print("\nSTATEWIDE TREND SUMMARY")

    for period_name, results in [
        ("ANNUAL", annual_results),
        ("JJAS MONSOON", monsoon_results)
    ]:

        state_rows = results[
            results["entity_type"]
            .astype(str)
            .str.lower()
            .eq("state")
        ]

        if state_rows.empty:
            state_rows = results[
                results["entity"]
                .astype(str)
                .str.lower()
                .isin(["maharashtra", "maharashtra state"])
            ]

        if not state_rows.empty:

            r = state_rows.iloc[0]

            print(f"\n{period_name}")
            print(
                "OLS trend: "
                f"{r['ols_slope_mm_per_decade']:.3f} "
                "mm/decade"
            )
            print(
                "HAC 95% CI: "
                f"[{r['hac_ci_lower_mm_per_decade']:.3f}, "
                f"{r['hac_ci_upper_mm_per_decade']:.3f}]"
            )
            print(
                f"HAC p-value: {r['hac_p_value']:.5f}"
            )
            print(
                f"Modified MK trend: {r['mk_trend']}"
            )
            print(
                f"Modified MK p-value: {r['mk_p_value']:.5f}"
            )
            print(
                "Sen's slope: "
                f"{r['sen_slope_mm_per_decade']:.3f} "
                "mm/decade"
            )
            print(
                "Residual lag-1 autocorrelation: "
                f"{r['residual_lag1_autocorrelation']:.3f}"
            )

    print("\nDistrict FDR results:")

    for period_name, results in [
        ("Annual", annual_results),
        ("JJAS", monsoon_results)
    ]:

        district_results = results[
            results["entity_type"]
            .astype(str)
            .str.lower()
            .eq("district")
        ]

        significant = int(
            district_results[
                "mk_fdr_significant_05"
            ].sum()
        )

        print(
            f"{period_name}: {significant} / "
            f"{len(district_results)} districts "
            "with MK q-value < 0.05"
        )

    print("\nFiles generated:")
