# 8. ANALYSE ALL ENTITIES
# ============================================================

def analyse_period(period_df, period_name):

    results = []
    sensitivity_records = []

    for (entity_type, entity), group in period_df.groupby(
        ["entity_type", "entity"],
        sort=True
    ):

        group = group.sort_values("year")

        years = group["year"].to_numpy(dtype=int)
        values = group["precipitation_mm"].to_numpy(
            dtype=float
        )

        if len(values) < MIN_YEARS:
            print(
                f"Skipping {entity}: "
                f"only {len(values)} observations."
            )
            continue

        # Check for consecutive annual observations.
        if not np.all(np.diff(years) == 1):
            raise ValueError(
                f"Non-consecutive years for {entity_type}: "
                f"{entity}. Inspect the annual series."
            )

        try:
            hac_result = calculate_hac_trend(
                years,
                values,
                MAIN_HAC_LAG
            )

            mk_result = calculate_mann_kendall(values)

        except Exception as exc:
            print(
                f"Analysis failed for {entity_type} "
                f"{entity}, {period_name}: {exc}"
            )
            continue

        record = {
            "period": period_name,
            "entity_type": entity_type,
            "entity": entity,
            "start_year": int(years[0]),
            "end_year": int(years[-1]),
            "n_years": len(years),
            "mean_precipitation_mm": float(
                np.mean(values)
            ),
            "std_precipitation_mm": float(
                np.std(values, ddof=1)
            ),
        }

        record.update(hac_result)
        record.update(mk_result)

        results.append(record)

        # ----------------------------------------------------
        # HAC sensitivity analysis
        # ----------------------------------------------------

        for lag in HAC_LAGS_TO_TEST:

            try:
                sensitivity = calculate_hac_trend(
                    years,
                    values,
                    lag
                )

                sensitivity_records.append({
                    "period": period_name,
                    "entity_type": entity_type,
                    "entity": entity,
                    "hac_lag": sensitivity["hac_maxlags"],
                    "slope_mm_per_decade": (
                        sensitivity[
                            "ols_slope_mm_per_decade"
                        ]
                    ),
                    "standard_error_mm_per_year": (
                        sensitivity[
                            "hac_standard_error_mm_per_year"
                        ]
                    ),
                    "ci_lower_mm_per_decade": (
                        sensitivity[
                            "hac_ci_lower_mm_per_decade"
                        ]
                    ),
                    "ci_upper_mm_per_decade": (
                        sensitivity[
                            "hac_ci_upper_mm_per_decade"
                        ]
                    ),
                    "p_value": sensitivity["hac_p_value"],
                })

            except Exception as exc:
                print(
                    f"HAC sensitivity failed for {entity}, "
                    f"lag {lag}: {exc}"
                )

    results_df = pd.DataFrame(results)
    sensitivity_df = pd.DataFrame(sensitivity_records)

    if results_df.empty:
        raise ValueError(
            f"No successful trend results for {period_name}."
        )

    # --------------------------------------------------------
    # FDR correction across districts only.
    # Statewide results are not included in the district family.
    # --------------------------------------------------------

    district_mask = (
        results_df["entity_type"]
        .astype(str)
        .str.lower()
        .eq("district")
    )

    results_df["mk_q_value"] = np.nan
    results_df["hac_q_value"] = np.nan

    results_df.loc[
        district_mask, "mk_q_value"
    ] = benjamini_hochberg(
        results_df.loc[
            district_mask, "mk_p_value"
        ].to_numpy()
    )

    results_df.loc[
        district_mask, "hac_q_value"
    ] = benjamini_hochberg(
        results_df.loc[
            district_mask, "hac_p_value"
        ].to_numpy()
    )

    results_df["mk_fdr_significant_05"] = (
        results_df["mk_q_value"] < ALPHA
    )

    results_df["hac_fdr_significant_05"] = (
        results_df["hac_q_value"] < ALPHA
    )

    results_df["mk_nominal_significant_05"] = (
        results_df["mk_p_value"] < ALPHA
    )

    return results_df, sensitivity_df


