def load_monthly_data(path):
    """Load and validate the district-level monthly panel."""

    if not path.exists():
        raise FileNotFoundError(
            f"Input CSV not found:\n{path}\n"
            "Check INPUT_CSV in the configuration section."
        )

    df = pd.read_csv(path)

    required = {
        "month",
        "entity_type",
        "entity",
        "monthly_precip_mm",
    }

    missing = required.difference(df.columns)

    if missing:
        raise ValueError(
            f"Missing required columns: {sorted(missing)}"
        )

    df["month"] = pd.to_datetime(
        df["month"],
        errors="coerce"
    )

    if df["month"].isna().any():
        raise ValueError("Invalid or missing month values found.")

    df["monthly_precip_mm"] = pd.to_numeric(
        df["monthly_precip_mm"],
        errors="coerce"
    )

    if not np.isfinite(
        df["monthly_precip_mm"].to_numpy(dtype=float)
    ).all():
        raise ValueError(
            "Missing or non-finite precipitation values found."
        )

    if (df["monthly_precip_mm"] < 0).any():
        raise ValueError(
            "Negative precipitation values found."
        )

    if df[
        ["entity_type", "entity"]
    ].isna().any().any():
        raise ValueError("Missing entity identifiers found.")

    # Each entity must have exactly one observation per month.
    duplicates = df.duplicated(
        subset=["entity_type", "entity", "month"]
    )

    if duplicates.any():
        raise ValueError(
            f"Found {duplicates.sum()} duplicate "
            "month/entity observations."
        )

    df["year"] = df["month"].dt.year
    df["month_number"] = df["month"].dt.month

    print("\nINPUT VALIDATION")
    print("-" * 55)
    print(f"Rows: {len(df):,}")
    print(f"Entities: {df['entity'].nunique()}")
    print(f"First month: {df['month'].min():%Y-%m}")
    print(f"Last month:  {df['month'].max():%Y-%m}")
    print(
        "Entity types:",
        df["entity_type"].value_counts().to_dict()
    )

    return df


