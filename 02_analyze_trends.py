# 3. BUILD COMPLETE ANNUAL AND MONSOON SERIES
# ============================================================

def aggregate_complete_periods(df):
    """
    Calculate annual and JJAS totals.

    Annual totals are retained only when all 12 distinct
    calendar months are present.

    JJAS totals are retained only when all four monsoon
    months are present.
    """

    annual_records = []
    monsoon_records = []

    grouped = df.groupby(
        ["entity_type", "entity"],
        sort=True
    )

    for (entity_type, entity), group in grouped:

        # ----------------------------------------------------
        # Annual totals
        # ----------------------------------------------------

        for year, year_data in group.groupby("year"):

            months_present = set(
                year_data["month_number"].tolist()
            )

            if months_present == set(range(1, 13)):
                annual_records.append({
                    "entity_type": entity_type,
                    "entity": entity,
                    "year": int(year),
                    "precipitation_mm": float(
                        year_data["monthly_precip_mm"].sum()
                    )
                })

        # ----------------------------------------------------
        # JJAS monsoon totals
        # ----------------------------------------------------

        monsoon_data = group[
            group["month_number"].isin(MONSOON_MONTHS)
        ]

        for year, year_data in monsoon_data.groupby("year"):

            months_present = set(
                year_data["month_number"].tolist()
            )

            if months_present == set(MONSOON_MONTHS):
                monsoon_records.append({
                    "entity_type": entity_type,
                    "entity": entity,
                    "year": int(year),
                    "precipitation_mm": float(
                        year_data["monthly_precip_mm"].sum()
                    )
                })

    annual = pd.DataFrame(annual_records)
    monsoon = pd.DataFrame(monsoon_records)

    if annual.empty:
        raise ValueError("No complete annual observations found.")

    if monsoon.empty:
        raise ValueError("No complete JJAS observations found.")

    annual.to_csv(
        OUTPUT_DIR / "annual_series.csv",
        index=False
    )

    monsoon.to_csv(
        OUTPUT_DIR / "monsoon_series.csv",
        index=False
    )

    print("\nAGGREGATION")
    print("-" * 55)
    print(
        f"Annual observations: "
        f"{annual['year'].min()}–{annual['year'].max()}"
    )
    print(
        f"JJAS observations: "
        f"{monsoon['year'].min()}–{monsoon['year'].max()}"
    )

    return annual, monsoon


