# 9. IDENTIFY THE STATEWIDE SERIES
# ============================================================

def get_statewide_row(period_df):

    state_mask = (
        period_df["entity_type"]
        .astype(str)
        .str.lower()
        .eq("state")
    )

    candidates = period_df[state_mask]

    if candidates.empty:
        candidates = period_df[
            period_df["entity"]
            .astype(str)
            .str.lower()
            .isin(["maharashtra", "maharashtra state"])
        ]

    if candidates.empty:
        raise ValueError(
            "Could not identify the statewide series. "
            "Check the entity_type and entity columns."
        )

    return candidates.iloc[0]["entity"]


